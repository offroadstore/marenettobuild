import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createHmac, randomBytes } from "node:crypto";
import { once } from "node:events";
import { createRequire } from "node:module";
import { createServer } from "node:net";
import { test, after, before } from "node:test";
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");

if (process.env.NODE_ENV === "production" || process.env.REPLIT_DEPLOYMENT === "1") {
  throw new Error("Run these tests only on the development database.");
}
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const schema = `test_requests_${randomBytes(8).toString("hex")}`;
const isolatedConnection = new URL(process.env.DATABASE_URL);
isolatedConnection.searchParams.set("options", `-c search_path=${schema}`);
const salt = randomBytes(32).toString("hex");
const valid = {
  requestType: "project", propertyType: "house", service: "renovation",
  location: "Cefalù (test)", projectStage: "planning", name: "Synthetic Test",
  email: "synthetic@example.invalid", preferredChannel: "email",
  message: "Synthetic fixture, not a real customer request.", preferredLanguage: "it",
  needsAccommodation: false, needsMobility: false, privacyAccepted: true,
  idempotencyKey: "phase-one-fixture-lead",
};
const clientIp = "192.0.2.21";
const rowHash = ip => createHmac("sha256", salt).update(ip).digest("hex");
const count = async table => (await pool.query(
  `SELECT count(*)::int AS n FROM ${schema}.${table}`,
)).rows[0].n;
let api, origin;

async function start() {
  const listener = createServer();
  listener.listen(0, "127.0.0.1");
  await once(listener, "listening");
  const { port } = listener.address();
  await new Promise(resolve => listener.close(resolve));
  origin = `http://127.0.0.1:${port}`;
  api = spawn(process.execPath, ["dist/index.mjs"], {
    stdio: ["ignore", "ignore", "inherit"],
    env: {
      ...process.env,
      DATABASE_URL: isolatedConnection.toString(),
      NODE_ENV: "production",
      PORT: String(port),
      PROJECT_REQUEST_IP_SALT: salt,
      MARENETTO_PRIVACY_APPROVED: "false",
      MARENETTO_PROVIDERS_APPROVED: "false",
      MARENETTO_TESTING_APPROVED: "false",
      MARENETTO_CSP_MODE: "report-only",
      ALLOWED_ORIGINS: "https://www.marenettobuild.com,https://marenettobuild.com",
    },
  });
  for (let attempt = 0; attempt < 80; attempt++) {
    if (api.exitCode !== null) throw new Error("Test API exited during startup.");
    if (await fetch(`${origin}/api/healthz`).then(r => r.ok, () => false)) return;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  throw new Error("Test API did not start.");
}

async function stop() {
  if (!api || api.exitCode !== null || api.signalCode !== null) return;
  const exited = once(api, "exit");
  api.kill();
  await exited;
}

function submit(overrides = {}, ip = clientIp) {
  return fetch(`${origin}/api/project-requests`, {
    method: "POST",
    headers: { "content-type": "application/json", "x-forwarded-for": ip },
    body: JSON.stringify({ ...valid, formOpenedAt: Date.now() - 6000, ...overrides }),
  });
}

before(async () => {
  await pool.query(`CREATE SCHEMA ${schema}`);
  // Copy only structure into the random test schema, never actual lead data
  // or public ID sequences. The child connections cannot resolve public tables.
  for (const table of ["project_requests", "internal_notifications", "project_request_attempts"]) {
    await pool.query(`CREATE TABLE ${schema}.${table} (LIKE public.${table} INCLUDING ALL)`);
    await pool.query(`ALTER TABLE ${schema}.${table} ALTER COLUMN id DROP DEFAULT, ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
  }
  await start();
});
after(async () => {
  try { await stop(); await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); }
  finally { await pool.end(); }
});

test("CORS allowlist and security headers cover success, preflight and errors", async () => {
  for (const site of ["https://external.example", "https://www.marenettobuild.com", "https://marenettobuild.com"]) {
    const r = await fetch(`${origin}/api/healthz`, { headers: { Origin: site } });
    assert.equal(r.status, 200);
    assert.equal(r.headers.get("access-control-allow-origin"), site.includes("external.example") ? null : site);
  }
  for (const [path, options, status] of [
    ["/api/healthz", { method: "HEAD" }, 200],
    ["/api/project-requests", { method: "OPTIONS", headers: { Origin: "https://marenettobuild.com", "Access-Control-Request-Method": "POST" } }, 204],
    ["/api/missing", {}, 404],
    ["/api/project-requests", { method: "POST", headers: { "content-type": "application/json" }, body: "{" }, 400],
  ]) {
    const r = await fetch(origin + path, options);
    assert.equal(r.status, status);
    for (const header of ["x-robots-tag", "x-frame-options", "referrer-policy", "permissions-policy", "x-content-type-options"]) {
      assert.ok(r.headers.get(header), header);
    }
    assert.match(r.headers.get("content-security-policy-report-only") ?? "", /^default-src 'self'/);
  }
});

for (const [label, payload] of [
  ["filled honeypot", () => ({ companyWebsite: "synthetic-test" })],
  ["faster than four seconds", () => ({ formOpenedAt: Date.now() - 1000 })],
]) test(`${label}: success response without lead, notification or reservation`, async () => {
  const r = await submit(payload());
  assert.equal(r.status, 201);
  assert.equal((await r.json()).status, "received");
  for (const table of ["project_requests", "internal_notifications", "project_request_attempts"]) assert.equal(await count(table), 0);
});

test("valid submission stores a synthetic lead and one notification", async () => {
  const r = await submit({ companyWebsite: "" });
  assert.equal(r.status, 201);
  assert.deepEqual(await r.json().then(({ status, isSynthetic }) => ({ status, isSynthetic })), { status: "received", isSynthetic: true });
  assert.equal(await count("project_requests"), 1);
  assert.equal(await count("internal_notifications"), 1);
  const { rows } = await pool.query(`SELECT ip_hash FROM ${schema}.project_request_attempts`);
  assert.deepEqual(rows, [{ ip_hash: rowHash(clientIp) }]);
});

test("five per ten minutes across concurrent requests and a restart", async () => {
  const ip = "192.0.2.23";
  const codes = await Promise.all(Array.from({ length: 7 }, () => submit({}, ip).then(r => r.status)));
  assert.deepEqual(codes.sort(), [200, 200, 200, 200, 200, 429, 429]);
  await stop();
  await start();
  assert.equal((await submit({}, ip)).status, 429);
});

test("twenty per rolling day, other IP unaffected, expired records purged on startup", async () => {
  const ip = "192.0.2.24";
  await pool.query(`INSERT INTO ${schema}.project_request_attempts (ip_hash, attempted_at) SELECT $1, now() - interval '2 hours' FROM generate_series(1, 19)`, [rowHash(ip)]);
  assert.equal((await submit({}, ip)).status, 200);
  assert.equal((await submit({}, ip)).status, 429);
  assert.equal((await submit({}, "192.0.2.25")).status, 200);
  await pool.query(`INSERT INTO ${schema}.project_request_attempts (ip_hash, attempted_at) VALUES ($1, now() - interval '25 hours')`, [rowHash(ip)]);
  await stop();
  await start();
  for (let attempt = 0; attempt < 50; attempt++) {
    const { rows } = await pool.query(`SELECT count(*)::int AS n FROM ${schema}.project_request_attempts WHERE attempted_at < now() - interval '24 hours'`);
    if (rows[0].n === 0) return;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.fail("Expired reservation was not removed.");
});
